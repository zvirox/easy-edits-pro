#!/usr/bin/env python3
"""Sample project generator + rot-guard (planning.md 6e E.2).

Builds the two maintained sample bundles with the REAL engine (saturn-cli
drives the same command dispatch the desktop app uses), then verifies the
saved files still open with the expected structure and render:

  First Cut          - import fixture, split on V1, set marks, add a marker,
                       add a title (renders as a GES title clip)
  Captions + Colour  - caption track with three cues, per-clip colour
                       adjustment, a timed marker, and a two-angle multicam
                       group (both angles point at the maintained fixture)

  --build DIR   generate the bundles into DIR (media copied beside the
                .saturn files so each directory is a self-contained bundle)
  --verify      build into a temp dir, then assert the persisted structure
                and render First Cut through the real GStreamer pipeline,
                verifying with ffprobe

Media provenance: the fixture is FFmpeg testsrc2 output generated by this
repository (see apps/saturn-tauri/tests/fixtures/README.md) - no
third-party footage. NOTE the format limitation the bundles carry: media
paths inside .saturn are absolute, so a bundle moved to another machine
shows its media offline until the existing relink flow is used. Recorded
in samples/README.md.
"""

import argparse
import json
import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CLI = REPO_ROOT / "target" / "debug" / "saturn-cli"
FIXTURE = REPO_ROOT / "apps" / "saturn-tauri" / "tests" / "fixtures" / "editor-smoke.webm"
TICKS_PER_SECOND = 254_016_000_000
BUNDLES = ("First Cut", "Captions and Colour")


def fail(step, message):
    print(f"FAIL [{step}] {message}", file=sys.stderr)
    sys.exit(1)


def step(name):
    print(f"[samples] {name}", flush=True)


def run(args, expect_zero=True):
    result = subprocess.run(args, capture_output=True, text=True, cwd=str(REPO_ROOT))
    if expect_zero and result.returncode != 0:
        fail(args[0], f"exit {result.returncode}: {result.stderr[:1500]}")
    return result


def ffprobe_json(path):
    return json.loads(run([
        "ffprobe", "-v", "error", "-print_format", "json",
        "-show_streams", "-show_format", str(path),
    ]).stdout)


def ticks(seconds):
    return round(float(seconds) * TICKS_PER_SECOND)


def control_session(project_path, requests, session_name):
    """Same JSONL contract as laptop_workflow.py: one `saturn-cli control
    --project` process, one response per request, all must be ok."""
    process = subprocess.Popen(
        [str(CLI), "control", "--project", str(project_path)],
        stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        text=True,
    )
    results = []
    for request in requests:
        process.stdin.write(json.dumps(
            {"id": request["id"], "params": request["params"]}) + "\n")
        process.stdin.flush()
        line = process.stdout.readline()
        if not line:
            fail(session_name, f"no response for {request['id']}: {process.stderr.read()}")
        response = json.loads(line)
        if not response.get("ok"):
            fail(session_name, f"{request['id']} rejected: {response.get('error')}")
        results.append(response.get("result"))
    process.stdin.close()
    remaining = process.stdout.read()
    process.wait(timeout=30)
    if process.returncode != 0:
        fail(session_name, f"control exited {process.returncode}: {process.stderr.read()}")
    if remaining.strip():
        fail(session_name, f"unexpected extra output: {remaining[:300]}")
    return results


def fixture_meta():
    probe = ffprobe_json(FIXTURE)
    video = next(s for s in probe["streams"] if s.get("codec_type") == "video")
    seconds = float(probe["format"]["duration"])
    numerator, _, denominator = video["avg_frame_rate"].partition("/")
    return {
        "name": FIXTURE.name,
        "path": FIXTURE,
        "kind": "video",
        "duration": ticks(seconds),
        "width": video["width"],
        "height": video["height"],
        "fps": round(int(numerator) / float(denominator or 1), 6),
        "codec": video.get("codec_name", "vp8"),
        "seconds": seconds,
    }


def build_bundle(target_dir: Path, meta) -> None:
    """Build both bundles into a fresh directory."""
    media_dir = target_dir / "media"
    media_dir.mkdir(exist_ok=True)
    footage = media_dir / "footage.webm"
    shutil.copy(FIXTURE, footage)
    angle_a = media_dir / "angle-a.webm"
    angle_b = media_dir / "angle-b.webm"
    shutil.copy(FIXTURE, angle_a)
    shutil.copy(FIXTURE, angle_b)

    # --- Bundle 1: First Cut -------------------------------------------------
    # Three control sessions: ids (media, new title track) are read back from
    # inspect between sessions. The title lives on its OWN video track -
    # the renderer stages one GES layer per track, so a title overlapping
    # the footage on V1 would not composite.
    project = target_dir / "First Cut.saturn"
    run([str(CLI), "new", str(project), "First Cut"])
    control_session(project, [
        {"id": "project.add_media", "params": {
            "name": "footage.webm", "path": str(footage), "kind": "video",
            "duration": meta["duration"], "width": meta["width"],
            "height": meta["height"], "fps": meta["fps"], "codec": meta["codec"],
        }},
        {"id": "file.save", "params": {"path": str(project)}},
    ], "first-cut-import")
    doc = json.loads(run([str(CLI), "inspect", str(project)]).stdout)
    media_id = doc["project"]["media"][0]["id"]
    track_id = next(
        t["id"] for t in doc["project"]["sequence"]["tracks"] if t["kind"] == "video"
    )
    control_session(project, [
        {"id": "timeline.add_clip", "params": {
            "track_id": track_id, "media_id": media_id,
        }},
        {"id": "timeline.split_clip", "params": {
            "track_id": track_id, "clip_index": 0,
            "at": ticks(meta["seconds"] / 2),
        }},
        {"id": "timeline.set_mark_in", "params": {"at": ticks(meta["seconds"] * 0.1)}},
        {"id": "timeline.set_mark_out", "params": {"at": ticks(meta["seconds"] * 0.9)}},
        {"id": "marker.add", "params": {
            "at": ticks(meta["seconds"] / 2), "name": "The split", "kind": "comment",
        }},
        {"id": "timeline.add_track", "params": {"kind": "video", "name": "Titles"}},
        {"id": "file.save", "params": {"path": str(project)}},
    ], "first-cut-edit")
    doc = json.loads(run([str(CLI), "inspect", str(project)]).stdout)
    title_track_id = max(
        t["id"] for t in doc["project"]["sequence"]["tracks"] if t["kind"] == "video"
    )
    control_session(project, [
        {"id": "timeline.add_title", "params": {
            "text": "First Cut", "subtitle": "Easy Edits Pro sample project",
            "duration": ticks(3), "track_id": title_track_id,
            "timeline_start": ticks(meta["seconds"] / 2),
        }},
        {"id": "file.save", "params": {"path": str(project)}},
    ], "first-cut-title")

    # --- Bundle 2: Captions and Colour ---------------------------------------
    project = target_dir / "Captions and Colour.saturn"
    run([str(CLI), "new", str(project), "Captions and Colour"])
    control_session(project, [
        {"id": "project.add_media", "params": {
            "name": "angle-a.webm", "path": str(angle_a), "kind": "video",
            "duration": meta["duration"], "width": meta["width"],
            "height": meta["height"], "fps": meta["fps"], "codec": meta["codec"],
        }},
        {"id": "project.add_media", "params": {
            "name": "angle-b.webm", "path": str(angle_b), "kind": "video",
            "duration": meta["duration"], "width": meta["width"],
            "height": meta["height"], "fps": meta["fps"], "codec": meta["codec"],
        }},
        {"id": "file.save", "params": {"path": str(project)}},
    ], "captions-import")
    doc = json.loads(run([str(CLI), "inspect", str(project)]).stdout)
    media_a_id, media_b_id = (m["id"] for m in doc["project"]["media"])
    video_track = next(t for t in doc["project"]["sequence"]["tracks"] if t["kind"] == "video")
    control_session(project, [
        {"id": "timeline.add_clip", "params": {
            "track_id": video_track["id"], "media_id": media_a_id,
        }},
        {"id": "caption.track_add", "params": {"name": "Sample captions", "language": "en"}},
        {"id": "caption.cue_add", "params": {
            "start_ticks": ticks(0.5), "end_ticks": ticks(2.0),
            "text": "Welcome to Easy Edits Pro.",
        }},
        {"id": "caption.cue_add", "params": {
            "start_ticks": ticks(2.2), "end_ticks": ticks(4.0),
            "text": "This sample carries a caption track with three cues.",
        }},
        {"id": "caption.cue_add", "params": {
            "start_ticks": ticks(4.2), "end_ticks": ticks(meta["seconds"] - 0.2),
            "text": "The colour and multicam panels also live here.",
        }},
        {"id": "marker.add", "params": {
            "at": ticks(2.2), "name": "Caption change", "kind": "comment",
            "note": "second cue starts",
        }},
        {"id": "clip.set_color", "params": {
            "track_id": video_track["id"], "clip_index": 0,
            "exposure": 0.15, "contrast": 1.1, "saturation": 1.2,
        }},
        {"id": "multicam.create", "params": {
            "name": "Sample two-angle",
            "angles": [
                {"id": 1, "name": "Angle A", "media_id": media_a_id},
                {"id": 2, "name": "Angle B", "media_id": media_b_id},
            ],
        }},
        {"id": "file.save", "params": {"path": str(project)}},
    ], "captions-edit")


def verify_bundle(dir_path: Path, meta) -> dict:
    """Assert the persisted .saturn files carry every expected element.
    Returns the checked facts for the PASS line."""
    expected = {}

    doc = json.loads(run([str(CLI), "inspect", str(dir_path / "First Cut.saturn")]).stdout)
    project = doc["project"]
    sequence = project["sequence"]
    video_tracks = [t for t in sequence["tracks"] if t["kind"] == "video"]
    if len(video_tracks) != 2:
        fail("verify", f"First Cut: expected 2 video tracks (V1 + Titles), got {len(video_tracks)}")
    edit_track = next(t for t in video_tracks if t["id"] == min(v["id"] for v in video_tracks))
    clips = edit_track["clips"]
    if len(clips) != 2:
        fail("verify", f"First Cut: expected 2 clips after the split on V1, got {len(clips)}")
    half = ticks(meta["seconds"]) // 2
    if clips[1]["source_in"] != half:
        fail("verify", f"First Cut: split retime lost ({clips[1]['source_in']} != {half})")
    if sequence.get("mark_in") is None or sequence.get("mark_out") is None:
        fail("verify", "First Cut: marks not persisted")
    if len(sequence.get("markers", [])) != 1:
        fail("verify", f"First Cut: expected 1 marker, got {len(sequence.get('markers', []))}")
    title_assets = [m for m in project["media"] if m.get("kind") == "title"]
    if len(title_assets) != 1 or title_assets[0]["title"]["text"] != "First Cut":
        fail("verify", f"First Cut: title asset wrong: {title_assets}")
    title_track = next(t for t in video_tracks if t["id"] == max(v["id"] for v in video_tracks))
    title_clips = title_track["clips"]
    if len(title_clips) != 1 or title_clips[0]["media_id"] != title_assets[0]["id"]:
        fail("verify", "First Cut: title clip missing from the Titles track")
    expected["first_cut_clips"] = len(clips)
    expected["title"] = title_assets[0]["title"]["text"]

    doc = json.loads(run(
        [str(CLI), "inspect", str(dir_path / "Captions and Colour.saturn")]
    ).stdout)
    project = doc["project"]
    sequence = project["sequence"]
    caption_tracks = sequence.get("caption_tracks", [])
    if len(caption_tracks) != 1:
        fail("verify", f"Captions: expected 1 caption track, got {len(caption_tracks)}")
    cues = caption_tracks[0].get("cues", [])
    if len(cues) != 3:
        fail("verify", f"Captions: expected 3 cues, got {len(cues)}")
    video_track = next(t for t in sequence["tracks"] if t["kind"] == "video")
    color = video_track["clips"][0]["color"]
    if not math.isclose(color.get("exposure", 0.0), 0.15, abs_tol=1e-6):
        fail("verify", f"Captions: colour grade lost (exposure {color.get('exposure')})")
    if not math.isclose(color.get("saturation", 1.0), 1.2, abs_tol=1e-6):
        fail("verify", f"Captions: colour grade lost (saturation {color.get('saturation')})")
    if len(sequence.get("multicam_clips", [])) != 1:
        fail("verify", f"Captions: expected 1 multicam group, got {sequence.get('multicam_clips', [])}")
    if len(sequence.get("markers", [])) != 1:
        fail("verify", f"Captions: expected 1 marker, got {len(sequence.get('markers', []))}")
    expected["cues"] = len(cues)
    expected["multicam"] = sequence["multicam_clips"][0]["name"]
    return expected


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--build", metavar="DIR", help="build the bundles into DIR")
    parser.add_argument("--verify", action="store_true",
                        help="fresh-build into a temp dir, assert structure, render")
    parser.add_argument("--keep", action="store_true", help="verify mode: keep the work dir")
    args = parser.parse_args()
    if not FIXTURE.is_file():
        fail("fixture", f"missing maintained fixture: {FIXTURE}")
    if not shutil.which("ffprobe"):
        fail("environment", "ffprobe must be on PATH")

    if args.build:
        target = Path(args.build)
        target.mkdir(parents=True, exist_ok=True)
        body = fixture_meta()
        build_bundle(target, body)
        print(f"[samples] built {len(BUNDLES)} bundles into {target}")
        return 0

    if not args.verify:
        fail("usage", "pass --build DIR or --verify")

    if not CLI.exists():
        run(["cargo", "build", "-q", "--bin", "saturn-cli"])
    if not CLI.exists():
        fail("build", "saturn-cli binary not found after cargo build")

    work = Path(tempfile.mkdtemp(prefix="eep-samples-"))
    step("build samples with the real engine")
    body = fixture_meta()
    build_bundle(work, body)
    step("verify persisted structure (rot-guard)")
    verify_bundle(work, body)
    step("render First Cut through the real GStreamer pipeline")
    output_path = work / "first-cut-out.mp4"
    rendered = run([str(CLI), "render", str(work / "First Cut.saturn"), str(output_path)])
    if "Rendered" not in rendered.stdout or not output_path.is_file():
        fail("render", f"render did not produce output: {rendered.stdout!r}")
    out = ffprobe_json(output_path)
    vstream = next((s for s in out["streams"] if s.get("codec_type") == "video"), None)
    if vstream is None or vstream.get("codec_name") != "h264":
        fail("ffprobe", f"expected an h264 video stream, got {vstream}")
    out_seconds = float(out["format"]["duration"])
    # Both split halves cover the full source (0-6s) on V1; the title is an
    # overlay on the Titles track, so expect roughly the source duration.
    if not (body["seconds"] - 1.0 <= out_seconds <= body["seconds"] + 1.0):
        fail("ffprobe", f"duration off: {out_seconds:.2f}s (expected ~{body['seconds']:.2f}s)")
    print(f"[samples] PASS - 2 bundles verified, render h264 "
          f"{vstream['width']}x{vstream['height']} {out_seconds:.2f}s, work dir {work}")
    if args.keep:
        print(f"[samples] kept work dir: {work}")
    else:
        shutil.rmtree(work, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
