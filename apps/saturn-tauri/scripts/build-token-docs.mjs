#!/usr/bin/env node
/**
 * Generates docs/glass-tokens.md from the live token files.
 * `--check` fails when the document is stale (used by CI).
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { auditContrast, parseThemes, resolveToken } from "./check-contrast.mjs";

const APP_ROOT = fileURLToPath(new URL("..", import.meta.url));
const DOC_PATH = join(APP_ROOT, "../../docs/glass-tokens.md");

const GROUPS = [
  {
    title: "Text and accents",
    tokens: [
      "--text-primary",
      "--text-secondary",
      "--text-muted",
      "--accent-text",
      "--accent-text-hover",
      "--accent-text-violet",
      "--text-on-accent",
    ],
  },
  {
    title: "Surfaces",
    tokens: [
      "--bg-canvas",
      "--bg-base",
      "--bg-surface",
      "--bg-elevated",
      "--bg-glass",
      "--bg-stage",
    ],
  },
  {
    title: "Glass",
    tokens: [
      "--glass-l1",
      "--glass-l2",
      "--glass-l3",
      "--glass-l4",
      "--glass-border",
      "--glass-highlight",
      "--glass-shadow",
      "--shadow-soft",
      "--shadow-soft-lg",
      "--glass-saturate",
      "--blur-l1",
      "--blur-l2",
      "--blur-l3",
      "--blur-l4",
    ],
  },
  {
    title: "Motion",
    tokens: ["--ease-spring", "--ease-out", "--dur-fast", "--dur-med", "--dur-slow"],
  },
];

function escapeCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function generate() {
  const themes = parseThemes();
  const { rows } = auditContrast();

  const lines = [
    "# Glass tokens",
    "",
    "<!-- Generated by apps/saturn-tauri/scripts/build-token-docs.mjs. Do not edit by hand. -->",
    "",
    "Semantic tokens come from `01-editor.css` and `00-tokens-glass.css`. Contrast",
    "pairs are enforced by `pnpm check:contrast` at WCAG AA (4.5:1).",
    "",
  ];

  for (const group of GROUPS) {
    lines.push(`## ${group.title}`, "", "| Token | Dark | Light |", "|---|---|---|");
    for (const token of group.tokens) {
      const dark = resolveToken(token, themes.dark) ?? "—";
      const light = resolveToken(token, themes.light) ?? "—";
      lines.push(`| \`${token}\` | \`${escapeCell(dark)}\` | \`${escapeCell(light)}\` |`);
    }
    lines.push("");
  }

  lines.push(
    "## Contrast matrix",
    "",
    "| Foreground | Background | Dark | Light | Minimum |",
    "|---|---|---:|---:|---:|",
  );
  for (const row of rows.filter((item) => item.foreground !== "--text-on-accent")) {
    const dark = rows.find(
      (item) =>
        item.theme === "dark" &&
        item.foreground === row.foreground &&
        item.background === row.background,
    );
    lines.push(
      `| \`${row.foreground}\` | \`${row.background}\` | ${dark?.ratio.toFixed(2) ?? "—"}:1 | ${row.ratio.toFixed(2)}:1 | ${row.minimum}:1 |`,
    );
  }
  lines.push("");
  lines.push(
    "White on accent surfaces:",
    "",
    "| Background | Dark | Light | Minimum |",
    "|---|---:|---:|---:|",
  );
  for (const row of rows.filter((item) => item.foreground === "--text-on-accent")) {
    const dark = rows.find(
      (item) =>
        item.theme === "dark" &&
        item.foreground === "--text-on-accent" &&
        item.background === row.background,
    );
    lines.push(
      `| \`${row.background}\` | ${dark?.ratio.toFixed(2) ?? "—"}:1 | ${row.ratio.toFixed(2)}:1 | ${row.minimum}:1 |`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

const check = process.argv.includes("--check");
const expected = generate();

if (check) {
  if (!existsSync(DOC_PATH) || readFileSync(DOC_PATH, "utf8") !== expected) {
    console.error("✗ docs/glass-tokens.md is stale; run `pnpm tokens:docs`");
    process.exitCode = 1;
  } else {
    console.log("✓ docs/glass-tokens.md is current");
  }
} else {
  writeFileSync(DOC_PATH, expected);
  console.log(`✓ wrote ${DOC_PATH}`);
}
