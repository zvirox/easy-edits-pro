class ReplSkin:
    """Interactive REPL for Easy Edits Pro."""
    
    def __init__(self, ctx: click.Context):
        self.ctx = ctx
        self.history: List[str] = []
        self.project = ctx.obj.get('project_state') or state.ProjectState.load_saved()
        self.history_path = self._history_path()
        self.readline = self._configure_readline()
    
    def run(self):
        """Enter REPL loop."""
        click.echo(f"Easy Edits Pro REPL v{__version__}")
        click.echo("Type 'help' for commands, 'exit' to quit")
        
        if self.project.current:
            click.echo(f"Project: {self.project.current.name}")
        
        try:
            while True:
                try:
                    prompt = "eep> " if not self.project.current else f"eep:{self.project.current.name}> "
                    line = input(prompt).strip()
                    if not line:
                        continue
                    if line in ('exit', 'quit'):
                        break
                    if line == 'help':
                        self.show_help()
                        continue
                    self.history.append(line)
                    if self.readline:
                        self.readline.add_history(line)
                    self.execute(line)
                except KeyboardInterrupt:
                    click.echo("\nUse 'exit' to quit")
                except EOFError:
                    break
                except Exception as error:
                    click.echo(f"Error: {error}")
        finally:
            self._save_history()
    
    def show_help(self):
        click.echo("""
Available commands:
  project create <name> [--template]    Create new project
  project open <path>                   Open existing project
  project save                          Save current project
  project close                         Close project
  
  timeline create <name> [--fps]        Create timeline
  timeline open <id>                    Open timeline
  timeline list                         List timelines
  
  track add <kind> [--name]             Add track (video/audio/subtitle)
  track remove <id>                     Remove track
  track list                            List tracks
  
  clip add <source> --track <id> [--at] Add clip to track
  clip move <id> --track <id> --at <t>  Move clip
  clip trim <id> --in <t> --out <t>     Trim clip
  clip remove <id>                      Remove clip
  
  render queue --preset <name> --out <path>  Queue render
  render status                         Show render queue
  
  undo                                  Undo last edit (Rust engine)
  redo                                  Redo last undone edit (Rust engine)
  history                               Show this CLI's command journal
  
  help                                  Show this help
  exit                                  Exit REPL
        """)
    
    def execute(self, line: str):
        """Dispatch a shell-like command through the same Click command tree."""
        parts = shlex.split(line)
        if not parts:
            return
        prefix = []
        if self.ctx.obj.get('output_json'):
            prefix.append('--json')
        project_path = self.ctx.obj.get('project_path')
        if project_path:
            prefix.extend(['--project', project_path])
        cli.main(args=prefix + parts, standalone_mode=False, obj=self.ctx.obj)
        self.project = self.ctx.obj.get('project_state') or self.project

    @staticmethod
    def _history_path() -> Path:
        state_root = Path(os.environ.get('XDG_STATE_HOME', Path.home() / '.local/state'))
        return state_root / 'easy-edits-pro' / 'repl_history'

    def _configure_readline(self):
        try:
            import readline
        except ImportError:
            return None
        self.history_path.parent.mkdir(parents=True, exist_ok=True)
        try:
            readline.read_history_file(str(self.history_path))
        except FileNotFoundError:
            pass
        readline.set_history_length(1000)
        readline.set_completer(self._complete)
        readline.parse_and_bind('tab: complete')
        return readline

    def _complete(self, text: str, index: int):
        buffer = self.readline.get_line_buffer() if self.readline else ''
        try:
            words = shlex.split(buffer)
        except ValueError:
            words = buffer.split()
        if buffer.endswith(' '):
            words.append('')
        if len(words) <= 1:
            candidates = list(cli.commands) + ['help', 'exit', 'quit']
        else:
            group = cli.commands.get(words[0])
            candidates = list(group.commands) if isinstance(group, click.Group) else []
        matches = [value for value in sorted(set(candidates)) if value.startswith(text)]
        return matches[index] if index < len(matches) else None

    def _save_history(self) -> None:
        if not self.readline:
            return
        try:
            self.history_path.parent.mkdir(parents=True, exist_ok=True)
            self.readline.write_history_file(str(self.history_path))
        except OSError as error:
            click.echo(f"Could not save REPL history: {error}", err=True)


