@click.group()
@click.version_option(__version__, '--version', '-V')
@click.option('--json', 'output_json', is_flag=True, help='Output JSON for agent consumption (implies --format json)')
@click.option('--format', 'output_format', type=click.Choice(['json', 'text', 'table']), default='text', help='Output format')
@click.option('--project', 'project_path', type=click.Path(exists=True), help='Project file to operate on')
@click.pass_context
def cli(ctx: click.Context, output_json: bool, output_format: str, project_path: Optional[str]):
    """Easy Edits Pro — Agent-native CLI for professional video editing."""
    ctx.ensure_object(dict)
    # --json implies --format json
    if output_json:
        output_format = 'json'
    ctx.obj['output_json'] = output_json
    ctx.obj['output_format'] = output_format
    ctx.obj['project_path'] = project_path
    
    # Initialize project state if path provided
    if project_path:
        state.ProjectState.load(project_path)


@cli.command()
@click.pass_context
def repl(ctx: click.Context):
    """Enter interactive REPL mode."""
    skin = ReplSkin(ctx)
    skin.run()


