@cli.command()
@click.pass_context
def undo(ctx: click.Context):
    """Undo last operation."""
    try:
        result = undo.UndoManager.undo()
        format_output(result, ctx.obj['output_format'])
    except EepError as e:
        format_output(e.to_dict(), ctx.obj['output_format'])
        sys.exit(1)


