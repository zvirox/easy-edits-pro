@click.group()
@click.version_option(__version__, '--version', '-V')
@click.option('--json', 'output_json', is_flag=True, help='Output JSON for agent consumption (implies --format json)')
@click.option('--format', 'output_format', type=click.Choice(['json', 'text', 'table']), default='text', help='Output format')
@click.option('--project', 'project_path', type=click.Path(exists=True), help='Project file to operate on')
@click.pass_context
def cli(ctx: click.Context, output_json: bool, output_format: str, project_path: Optional[str]):
    """Easy Edits Pro — Agent-native CLI for professional video editing."""
    ctx.ensure_object(dict)
    # --json implies --format json
    if output_json:
        output_format = 'json'
    ctx.obj['output_json'] = output_json
    ctx.obj['output_format'] = output_format
    ctx.obj['project_path'] = project_path
    
    # Initialize project state if path provided
    if project_path:
        try:
            loaded_state = state.ProjectState.load(project_path)
        except ValueError as error:
            raise EepError(ErrorCode.PROJECT_INVALID, str(error), details={"path": project_path}, recoverable=False) from error
        ctx.obj['project_state'] = loaded_state
        cli_backend = backend.get_saturn_cli()
        resolved_path = str(Path(project_path).expanduser().resolve())
        if cli_backend.current_path != resolved_path:
            cli_backend.project_open(resolved_path)
        loaded_state.save()
    else:
        loaded_state = state.ProjectState.load_saved()
        ctx.obj['project_state'] = loaded_state
        if loaded_state.current and Path(loaded_state.current.path).is_file():
            cli_backend = backend.get_saturn_cli()
            if cli_backend.current_path != loaded_state.current.path:
                cli_backend.project_open(loaded_state.current.path)


@cli.command()
@click.pass_context
def repl(ctx: click.Context):
    """Enter interactive REPL mode."""
    skin = ReplSkin(ctx)
    skin.run()


